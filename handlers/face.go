// face 段出站转换: QQ 官方 bot 消息接口只接受文本(content, 含 Unicode emoji),
// 无法发送 onebot v11 的数字表情(face id)。send_group_msg / send_msg 的段转换
// (parseMessageContent) 原本没有 case "face", 表情段会落入 default 被静默丢弃
// (日志 "Unhandled segment type: face") —— 表现为"发出去表情没了"。
//
// 修复: 常用 QQ 表情 id 映射为近似 Unicode emoji 文本(官方通道可发、QQ 客户端
// 会渲染为原生表情); 未收录的 id 回退为可读占位 "[表情:<id>]", 保证消息不丢
// 内容、不中断后续段。需要更全的映射可自行扩展 faceEmojiMap。

func faceIDToEmoji(id string) string {
	if emoji, ok := faceEmojiMap[id]; ok {
		return emoji
	}
	return "[表情:" + id + "]"
}

