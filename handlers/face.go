// face 段出站转换 —— 终稿。
//
// 官方 bot 能力表(2026-08-31, https://bot.q.qq.com/wiki/develop/api-v2/):
// 消息类型只有 文本 / Markdown / 图片 / 视频 / 语音 / 文件 / 结构化卡片 / Embed /
// 表情表态 / 引用消息 —— **没有"表情"作为消息内容**这一项(表情表态=给消息点赞,
// 不是发送表情)。因此 onebot v11 的 face 段(数字表情)在官方 bot 通道**从根上
// 不存在**:
//   - <emoji:ID> 纯文本通道实测显示原文;
//   - <emoji:ID> markdown 通道实测同样不渲染;
//   - Unicode emoji 字符方案实测行不通。
//
// 三条路全部证伪后, face 段降级为可读占位 "[表情名]"(如 [微笑]); 未收录 id 用
// "[表情:<id>]" 兜底。不丢内容、不中断后续段、不触发 markdown 升级。
//
// faceNameMap 是两套编号体系的**合并**, 优先以 QQNT 官方面板为准:
//   1. 主表: QQNT 客户端官方表情面板
//      (C:\Program Files\Tencent\QQNT\...\resource\default-emojis\default_config.json,
//       normalPanelResult.SysEmojiGroupList[].SysEmojiList[], emojiId -> describe 去 "/" 前缀),
//       含新版表情 id 0~431(小黄脸 + 超级/大表情, 含捂脸264/吃瓜271/拜谢297/蛇年429 等)
//   2. 补充: 互联网 face_config.json 的 sysface 段, 补入 QQNT 面板未列出的经典 id
//      (如 54闪电/55炸弹/57足球/122爱你/145祈祷/113啤酒/117瓢虫, 以及 214~244 CM 动态表情)
// 同 id 冲突时以 QQNT 为准。未收录 id 用 "[表情:<id>]" 兜底。
// 若未来 QQ 开放平台支持表情消息, 只需改造 faceIDToEmoji 把名字替换成官方真实
// 格式, faceNameMap 继续复用。

func faceIDToEmoji(id string) string {
	if id == "" {
		return ""
	}
	if name, ok := faceNameMap[id]; ok {
		return "[" + name + "]"
	}
	return "[表情:" + id + "]"
}

